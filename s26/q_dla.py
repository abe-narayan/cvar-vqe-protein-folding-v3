"""s26/q_dla.py -- the DYNAMICAL LIE ALGEBRA of the deployed ansatz and of the ADAPT pools.

PROPERTY MEASUREMENT (A2, s26/PREREG_A2.md).  Reads no RMSD, no native.  It exists because
s25/QUANTUM.md section 7.1 says "NOT MEASURED: the dynamical Lie algebra actually generated by
{Y_q} and the CNOT-chain conjugations at fixed depth" (open item 4 of the state brief).

THE CONSTRUCTION
================
The deployed circuit is U = C R_L C R_{L-1} ... C R_1 on |0...0>, with R_l = prod_q RY(theta_{l,q})
= prod_q exp(-i theta_{l,q} Y_q / 2) and C the CNOT chain plus ring closure (a Clifford).  Moving
every C to the right,

    U = [C R_L C^-1] [C^2 R_{L-1} C^-2] ... [C^L R_1 C^-L] C^L,

so the parameter theta_{l,q} generates the Pauli string P_{l,q} = C^{L-l+1} Y_q C^{-(L-l+1)}
(a single string up to sign, because C is Clifford), and the trailing C^L is a fixed
permutation of the computational basis which changes no probability up to relabelling and
no Lie algebra at all.  Moving the C's to the LEFT instead gives the conjugate set
{C^{-k} Y_q C^{k} : k = 0..L-1}, related to this one by conjugation with C^L; the two
algebras are isomorphic and have the same dimension, and the test file checks it.

The dynamical Lie algebra (DLA) is the real Lie closure of {-i P_{l,q} / 2}.  The commutator
of two Pauli strings is zero if they commute and (up to a scalar) their product string if they
anticommute, so the closure can be computed EXACTLY on Pauli strings as a SET: represent a string
by bit vectors (x, z); two strings anticommute iff the symplectic product x.z' + z.x' is odd;
the product is (x ^ x', z ^ z').  Distinct strings are linearly independent, and the Lie algebra
generated by a set is spanned by right-normed nested commutators [g_1,[g_2,[...,g_k]]], each of
which is a scalar times a string reached by commuting generators into the current string; so
dim(DLA) = the size of the closure under "commute with a generator", found by breadth-first
search.  A cap (2^21 = 2,097,152 strings, the smallest power of two that holds so(2^11)) stops
the search on registers whose closure would not fit.

Every Y_q has one Y and CNOT conjugation preserves the parity of the Y count, so every P_{l,q}
has an ODD number of Y's; such strings are imaginary antisymmetric, -iP/2 is real antisymmetric,
and the odd-Y strings span exactly so(2^n): their number is (4^n - 2^n)/2 = 2^(n-1)(2^n - 1) =
dim so(2^n).  The closure is checked to stay inside that set.

CROSS-CHECK
===========
At n = 4 and 5 the same closure is computed numerically: nested commutators of dense matrices
-iP/2, rank by SVD with a relative tolerance of 1e-10, iterated to convergence.  The two routes
must agree exactly on the dimension.

THE ADAPT SETS
==============
For each ADAPT pool (V, G, L2 of s26/q_adapt.py) the closure of the WHOLE pool is reported, and
for the operator sequences ADAPT selects on the deployed energy shape (standardised ranks
1..2^n, the two VQE_LFO cells) the closure of the selected strings (initial RY layer included)
at every growth step.

Artefact: s26/results/q_dla.json (s24.stats_lib.save_atomic, resumable per n).
"""
